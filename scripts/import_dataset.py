#!/usr/bin/env python3
"""Validate the entire CSV/image pool and emit a transactional, server-only SQL seed."""
import argparse
import csv
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def number(value):
    n = float(value)
    if not math.isfinite(n) or n < 0:
        raise ValueError(f"Expected finite non-negative number: {value!r}")
    return n

def load_study_trials(csv_path, image_dir):
    trials, ids, dishes = [], set(), set()
    with open(csv_path, newline='', encoding='utf-8-sig') as source:
        for row in csv.DictReader(source):
            trial_id, dish_id = row['trial_id'].strip(), row['dish_id'].strip()
            if not trial_id or not dish_id or trial_id in ids or dish_id in dishes:
                raise ValueError('Trial IDs and dish IDs must be nonempty and unique.')
            filename = Path(row['image_path']).name
            if not (image_dir / filename).is_file():
                raise ValueError(f'Missing meal image: {filename}')
            ingredients = json.loads(row['model_ingredients_json'])
            if not isinstance(ingredients, list):
                raise ValueError('model_ingredients_json must be an array')
            parsed = []
            for item in ingredients:
                if not isinstance(item.get('name'), str) or not item['name'].strip():
                    raise ValueError('Each ingredient needs a name')
                ingredient = {'name': item['name'], 'kcal': number(item['kcal'])}
                if item.get('grams') is not None:
                    ingredient['grams'] = number(item['grams'])
                parsed.append(ingredient)
            trials.append(dict(trial_id=trial_id, dish_id=dish_id,
                image_path='/study_images/' + filename,
                ground_truth_kcal=number(row['ground_truth_kcal']),
                model_total_kcal=number(row['model_total_kcal']), ingredients=parsed))
            ids.add(trial_id); dishes.add(dish_id)
    if not trials:
        raise ValueError('Dataset is empty')
    return trials

def sql_string(value):
    return "'" + value.replace("'", "''") + "'"

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--csv', type=Path, default=ROOT/'data/study_dataset.csv')
    parser.add_argument('--images', type=Path, default=ROOT/'public/study_images')
    parser.add_argument('--output', type=Path, default=ROOT/'supabase/calorie_seed.sql')
    args = parser.parse_args()
    trials = load_study_trials(args.csv, args.images)
    sql = ['-- Generated by scripts/import_dataset.py. Never serve this file publicly.', 'begin;']
    for t in trials:
        values = [sql_string(t['trial_id']), sql_string(t['dish_id']), sql_string(t['image_path']),
                  str(t['ground_truth_kcal']), str(t['model_total_kcal']), sql_string(json.dumps(t['ingredients']))+'::jsonb']
        sql.append('insert into public.meal_trials (trial_id,dish_id,image_path,ground_truth_kcal,model_total_kcal,ingredients) values (' + ','.join(values) + ') on conflict (trial_id) do nothing;')
    sql.append('commit;')
    args.output.write_text('\n'.join(sql)+'\n')
    print(f'Validated {len(trials)} unique meals and images; wrote {args.output}')

if __name__ == '__main__':
    main()
